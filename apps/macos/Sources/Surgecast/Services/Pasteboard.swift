import AppKit
import CryptoKit

@MainActor final class Pasteboard {
  private var timer: Timer?
  private var count = NSPasteboard.general.changeCount
  private var ignored = Set<String>()
  private let hub: EventHub
  init(hub: EventHub) { self.hub = hub }
  func monitor(_ p: [String: Any]) throws {
    timer?.invalidate()
    timer = nil
    ignored = Set(p["ignoredBundleIds"] as? [String] ?? [])
    guard try p.boolean("enabled") else { return }
    let ms = p["intervalMs"] as? Double ?? 300
    guard ms >= 50 && ms <= 60000 else {
      throw RpcError.invalid("Polling interval must be 50...60000ms")
    }
    count = NSPasteboard.general.changeCount
    timer = Timer.scheduledTimer(withTimeInterval: ms / 1000, repeats: true) { [weak self] _ in
      Task { @MainActor in self?.changed() }
    }
  }
  func stop() { timer?.invalidate() }
  private func changed() {
    let board = NSPasteboard.general
    guard board.changeCount != count else { return }
    count = board.changeCount
    let source = NSWorkspace.shared.frontmostApplication
    if let id = source?.bundleIdentifier, ignored.contains(id) { return }
    Task {
      if var snapshot = try? await read() {
        snapshot["sourceApp"] = source?.bundleURL.map(Applications.info)
        hub.emit("clipboard.changed", snapshot)
      }
    }
  }
  func read() async throws -> [String: Any]? {
    let pb = NSPasteboard.general
    let types = (pb.types ?? []).map(\.rawValue)
    guard !types.isEmpty else { return nil }
    var o: [String: Any] = [
      "changeCount": pb.changeCount, "types": types,
      "concealed": types.contains("org.nspasteboard.ConcealedType"),
      "transient": types.contains("org.nspasteboard.TransientType")
        || types.contains("org.nspasteboard.AutoGeneratedType"),
    ]
    let text = pb.string(forType: .string)
    let html = pb.string(forType: .html)
    o["text"] = text
    o["html"] = html
    var primary: [String: Any]?
    if let files = pb.readObjects(
      forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !files.isEmpty
    {
      primary = ["kind": "file", "paths": files.map(\.path)]
    } else if let image = NSImage(pasteboard: pb), let tiff = image.tiffRepresentation,
      let bitmap = NSBitmapImageRep(data: tiff),
      let png = bitmap.representation(using: .png, properties: [:])
    {
      let hash = SHA256.hash(data: png).map { String(format: "%02x", $0) }.joined()
      let file = Environment.dataDir.appendingPathComponent("clipboard/\(hash).png")
      let width = bitmap.pixelsWide
      let height = bitmap.pixelsHigh
      try await Task.detached {
        if !FileManager.default.fileExists(atPath: file.path) {
          try png.write(to: file, options: .atomic)
        }
      }.value
      primary = [
        "kind": "image", "path": file.path, "uti": "public.png", "width": width, "height": height,
      ]
    } else if let color = NSColor(from: pb)?.usingColorSpace(.deviceRGB) {
      primary = [
        "kind": "color",
        "hex": String(
          format: "#%02x%02x%02x", Int(color.redComponent * 255), Int(color.greenComponent * 255),
          Int(color.blueComponent * 255)),
      ]
    } else if text != nil || html != nil || pb.data(forType: .rtf) != nil {
      var value: [String: Any] = ["kind": "text", "text": text ?? ""]
      value["html"] = html
      value["rtf"] = pb.data(forType: .rtf).map { String(decoding: $0, as: UTF8.self) }
      primary = value
    }
    guard let primary else { return nil }
    o["primary"] = primary
    o["sourceApp"] = Applications.running(NSWorkspace.shared.frontmostApplication).map {
      var a = $0
      a.removeValue(forKey: "pid")
      a.removeValue(forKey: "isActive")
      a.removeValue(forKey: "isHidden")
      return a
    }
    return o
  }
  func write(_ content: [String: Any], concealed: Bool = false, transient: Bool = false) throws {
    let item = NSPasteboardItem()
    switch try content.string("kind") {
    case "text":
      guard let text = content["text"] as? String else { throw RpcError.invalid("Missing text") }
      item.setString(text, forType: .string)
      if let html = content["html"] as? String { item.setString(html, forType: .html) }
      if let rtf = content["rtf"] as? String { item.setData(Data(rtf.utf8), forType: .rtf) }
    case "file":
      let paths = try content.strings("paths")
      guard !paths.isEmpty else { throw RpcError.invalid("Empty file list") }
      let pb = NSPasteboard.general
      pb.clearContents()
      pb.writeObjects(paths.map { NSURL(fileURLWithPath: $0) })
      if concealed {
        pb.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"))
      }
      if transient {
        pb.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
      }
      count = pb.changeCount
      return
    case "image":
      let image: NSImage?
      if let path = content["path"] as? String {
        image = NSImage(contentsOfFile: path)
      } else if let base64 = content["base64"] as? String, let data = Data(base64Encoded: base64) {
        image = NSImage(data: data)
      } else {
        image = nil
      }
      guard let image, let tiff = image.tiffRepresentation else {
        throw RpcError.invalid("Invalid image")
      }
      item.setData(tiff, forType: .tiff)
    case "color":
      let hex = try content.string("hex").trimmingCharacters(in: CharacterSet(charactersIn: "#"))
      guard hex.count == 6 || hex.count == 8, let n = UInt64(hex, radix: 16) else {
        throw RpcError.invalid("Expected #RRGGBB or #RRGGBBAA")
      }
      let shift = hex.count == 8 ? 8 : 0
      let color = NSColor(
        srgbRed: CGFloat((n >> (16 + shift)) & 255) / 255,
        green: CGFloat((n >> (8 + shift)) & 255) / 255, blue: CGFloat((n >> shift) & 255) / 255,
        alpha: hex.count == 8 ? CGFloat(n & 255) / 255 : 1)
      let pb = NSPasteboard.general
      pb.clearContents()
      color.write(to: pb)
      pb.setString("#" + hex, forType: .string)
      if concealed {
        pb.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"))
      }
      if transient {
        pb.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
      }
      count = pb.changeCount
      return
    default: throw RpcError.invalid("Unknown clipboard content kind")
    }
    if concealed {
      item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"))
    }
    if transient {
      item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
    }
    NSPasteboard.general.clearContents()
    guard NSPasteboard.general.writeObjects([item]) else {
      throw RpcError.failure("Cannot write clipboard")
    }
    count = NSPasteboard.general.changeCount
  }
  func saved() -> [[NSPasteboard.PasteboardType: Data]] {
    (NSPasteboard.general.pasteboardItems ?? []).map { item in
      var data: [NSPasteboard.PasteboardType: Data] = [:]
      for type in item.types { data[type] = item.data(forType: type) }
      return data
    }
  }
  func restore(_ saved: [[NSPasteboard.PasteboardType: Data]], ifCount: Int? = nil) {
    let pb = NSPasteboard.general
    if let ifCount, pb.changeCount != ifCount { return }
    pb.clearContents()
    let items = saved.map { entries -> NSPasteboardItem in
      let item = NSPasteboardItem()
      for (type, data) in entries { item.setData(data, forType: type) }
      return item
    }
    pb.writeObjects(items)
    count = pb.changeCount
  }
}
