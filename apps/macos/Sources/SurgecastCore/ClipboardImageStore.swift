import Foundation

public enum ClipboardImageStore {
  public static func isPrivate(_ types: [String]) -> Bool {
    types.contains("org.nspasteboard.ConcealedType")
      || types.contains("org.nspasteboard.TransientType")
      || types.contains("org.nspasteboard.AutoGeneratedType")
  }

  public static func content(png: Data, file: URL, width: Int, height: Int, types: [String]) throws -> [String: Any] {
    var content: [String: Any] = ["kind": "image", "uti": "public.png", "width": width, "height": height]
    if isPrivate(types) {
      content["base64"] = png.base64EncodedString()
    } else {
      if !FileManager.default.fileExists(atPath: file.path) {
        try png.write(to: file, options: .atomic)
      }
      content["path"] = file.path
    }
    return content
  }
}
