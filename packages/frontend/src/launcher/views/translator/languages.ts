const BY_CODE = new Map(LANGUAGES.map((l) => [l.code.toLowerCase(), l]));
const BY_NAME = new Map(LANGUAGES.map((l) => [l.name.toLowerCase(), l]));

/** Older or regional codes models and systems still report. */
const ALIASES: Record<string, string> = {
  iw: "he",
  jw: "jv",
  tl: "fil",
  nb: "no",
  nn: "no",
  "zh-cn": "zh",
  "zh-sg": "zh",
  "zh-hans": "zh",
  "zh-hk": "zh-TW",
  "zh-mo": "zh-TW",
  "zh-hant": "zh-TW",
  chinese: "zh",
};

/**
 * Map a code or English name ("es", "ES", "pt-BR", "zh_Hant", "Spanish") to a
 * language in `LANGUAGES`; null when unknown.
 */
export function normalizeLanguageCode(raw: string | null | undefined): string | null {
  if (!raw) return null;
  const key = raw.trim().toLowerCase().replace(/_/g, "-");
  if (!key) return null;
  const alias = ALIASES[key];
  if (alias) return alias;
  const exact = BY_CODE.get(key) ?? BY_NAME.get(key);
  if (exact) return exact.code;
  const base = key.split("-")[0];
  return ALIASES[base] ?? BY_CODE.get(base)?.code ?? null;
}

export function isLanguage(code: string): boolean {
  return BY_CODE.has(code.toLowerCase());
}

export function languageName(code: string): string {
  if (code === AUTO_LANGUAGE) return "Detect Language";
  return BY_CODE.get(code.toLowerCase())?.name ?? code;
}
