import { describe, expect, it } from "vitest";
import type { ClipboardSnapshot } from "@opencast/protocol";
import {
  classifyClipboard,
  retentionMs,
} from "../../src/services/core/clipboard";
const snapshot = (text: string): ClipboardSnapshot => ({
  changeCount: 1,
  primary: { kind: "text", text },
  types: [],
  concealed: false,
  transient: false,
});
describe("clipboard classification", () => {
  it.each([
    ["hello\nworld", "text"],
    ["https://example.com/path", "link"],
    ["mailto:hello@example.com", "link"],
    ["#fff", "color"],
    ["rgb(255, 0, 0)", "color"],
    ["https://example.com text", "text"],
  ])("classifies %s", (text, kind) =>
    expect(classifyClipboard(snapshot(text))?.kind).toBe(kind),
  );
  it("deduplicates content independent of source and timestamp", () => {
    expect(classifyClipboard(snapshot("hello"))?.contentHash).toBe(
      classifyClipboard({
        ...snapshot("hello"),
        sourceApp: { name: "App", path: "/app" },
      })?.contentHash,
    );
  });
  it("skips empty, concealed, transient and autogenerated values", () => {
    expect(classifyClipboard(snapshot(""))).toBeNull();
    expect(
      classifyClipboard({ ...snapshot("secret"), concealed: true }),
    ).toBeNull();
    expect(
      classifyClipboard({ ...snapshot("temp"), transient: true }),
    ).toBeNull();
    expect(
      classifyClipboard({
        ...snapshot("temp"),
        types: ["org.nspasteboard.AutoGeneratedType"],
      }),
    ).toBeNull();
  });
  it("classifies image and file metadata", () => {
    expect(
      classifyClipboard({
        ...snapshot(""),
        primary: {
          kind: "image",
          path: "/image.png",
          width: 1280,
          height: 800,
        },
      }),
    ).toMatchObject({ kind: "image", title: "Image (1280×800)" });
    expect(
      classifyClipboard({
        ...snapshot(""),
        primary: { kind: "file", paths: ["/tmp/test.txt"] },
      }),
    ).toMatchObject({ kind: "file", title: "test.txt" });
  });
  it("handles finite and unlimited retention", () => {
    expect(retentionMs("90d")).toBe(90 * 86400000);
    expect(retentionMs("unlimited")).toBeNull();
    expect(retentionMs("never")).toBe(0);
  });
});
