import { createHash, randomUUID } from "node:crypto";
import { readFile, mkdir, writeFile, unlink } from "node:fs/promises";
import { basename, join, dirname } from "node:path";
import type {
  ClipboardContent,
  ClipboardItem,
  ClipboardSnapshot,
} from "@surgecast/protocol";
import type { AppContext, Service } from "../../context";
import { background, boundedLimit, ftsQuery } from "./shared";
import { parseColor } from "./colors";
import { RpcError } from "../../util/errors";

export function classifyClipboard(
  snapshot: ClipboardSnapshot,
  imagePath?: string,
  imageHash?: string,
): ClipboardItem | null {
  if (
    snapshot.concealed ||
    snapshot.transient ||
    snapshot.types.some((t) =>
      /org\.nspasteboard\.(?:ConcealedType|TransientType|AutoGeneratedType)/i.test(
        t,
      ),
    )
  )
    return null;
  const primary = snapshot.primary;
  const now = Date.now();
  let fields: Partial<ClipboardItem>;
  if (primary.kind === "image") {
    const path = imagePath ?? primary.path;
    if (!path && !primary.base64) return null;
    fields = {
      kind: "image",
      imagePath: path,
      imageWidth: primary.width,
      imageHeight: primary.height,
      title:
        primary.width && primary.height
          ? `Image (${primary.width}×${primary.height})`
          : "Image",
    };
  } else if (primary.kind === "file") {
    if (!primary.paths.length) return null;
    fields = {
      kind: "file",
      filePaths: primary.paths,
      title:
        primary.paths.length === 1
          ? basename(primary.paths[0])
          : `${primary.paths.length} Files`,
      text: snapshot.text ?? primary.paths.join("\n"),
    };
  } else {
    const text = primary.kind === "color" ? primary.hex : primary.text;
    if (!text.trim()) return null;
    const color = parseColor(text.trim());
    let url: string | undefined;
    try {
      const parsed = new URL(text.trim());
      if (
        ["http:", "https:", "mailto:"].includes(parsed.protocol) &&
        !/\s/.test(text.trim())
      )
        url = parsed.href;
    } catch {
      /* ordinary text */
    }
    fields = {
      kind: color ? "color" : url ? "link" : "text",
      text,
      html:
        primary.kind === "text" ? (primary.html ?? snapshot.html) : undefined,
      title: text.split(/\r?\n/)[0].slice(0, 250),
      color: color?.hex,
      url,
      characters: [...text].length,
      words: text.trim().split(/\s+/u).length,
      byteSize: Buffer.byteLength(text),
    };
  }
  const canonical =
    primary.kind === "image"
      ? (imageHash ?? primary.base64 ?? primary.path)
      : primary.kind === "file"
        ? JSON.stringify(primary.paths)
        : JSON.stringify([fields.text, fields.html]);
  const contentHash = createHash("sha256")
    .update(`${fields.kind}:${canonical}`)
    .digest("hex");
  return {
    ...fields,
    id: randomUUID(),
    contentHash,
    sourceApp: snapshot.sourceApp,
    pinned: false,
    copyCount: 1,
    createdAt: now,
    lastCopiedAt: now,
  } as ClipboardItem;
}
export function retentionMs(duration: string): number | null {
  if (duration === "never" || duration === "immediately") return 0;
  if (duration === "unlimited") return null;
  const m = /^(\d+)([smhdwy])$/.exec(duration);
  return m
    ? Number(m[1]) *
        {
          s: 1000,
          m: 60000,
          h: 3600000,
          d: 86400000,
          w: 604800000,
          y: 31536000000,
        }[m[2]]!
    : null;
}
interface Row {
  id: string;
  data: string;
}
export function clipboardItems(ctx: AppContext, limit = 50): ClipboardItem[] {
  return ctx.db
    .all<Row>(
      "SELECT id,data FROM clipboard_history ORDER BY last_copied_at DESC LIMIT ?",
      limit,
    )
    .map((r) => JSON.parse(r.data));
}
export function clipboardContent(
  item: ClipboardItem,
  plainText = false,
): ClipboardContent {
  if (plainText || item.kind === "text" || item.kind === "link")
    return {
      kind: "text",
      text: item.text ?? item.title,
      html: plainText ? undefined : item.html,
    };
  if (item.kind === "image")
    return {
      kind: "image",
      path: item.imagePath,
      width: item.imageWidth,
      height: item.imageHeight,
    };
  if (item.kind === "file")
    return { kind: "file", paths: item.filePaths ?? [] };
  return { kind: "color", hex: item.color! };
}
export const clipboardService: Service = {
  name: "core.clipboard",
  register(ctx) {
    ctx.db.addMigrations({
      id: "core-clipboard-001",
      up: `
    CREATE TABLE clipboard_history (id TEXT PRIMARY KEY, content_hash TEXT UNIQUE NOT NULL, kind TEXT NOT NULL, pinned INTEGER NOT NULL, last_copied_at INTEGER NOT NULL, data TEXT NOT NULL);
    CREATE INDEX clipboard_recency ON clipboard_history(last_copied_at DESC);
    CREATE VIRTUAL TABLE clipboard_fts USING fts5(id UNINDEXED, title, text);
  `,
    });
    const imageDir = join(ctx.dataDir, "clipboard");
    const get = (id: string) => {
      const row = ctx.db.get<Row>(
        "SELECT id,data FROM clipboard_history WHERE id = ?",
        id,
      );
      return row ? (JSON.parse(row.data) as ClipboardItem) : null;
    };
    const required = (id: string) => {
      const item = get(id);
      if (!item) throw RpcError.notFound(`Clipboard item ${id}`);
      return item;
    };
    const persist = (item: ClipboardItem) => {
      ctx.db.transaction(() => {
        ctx.db.run(
          "INSERT INTO clipboard_history VALUES (?,?,?,?,?,?) ON CONFLICT(id) DO UPDATE SET pinned=excluded.pinned,last_copied_at=excluded.last_copied_at,data=excluded.data",
          item.id,
          item.contentHash,
          item.kind,
          Number(item.pinned),
          item.lastCopiedAt,
          JSON.stringify(item),
        );
        ctx.db.run("DELETE FROM clipboard_fts WHERE id = ?", item.id);
        ctx.db.run(
          "INSERT INTO clipboard_fts VALUES (?,?,?)",
          item.id,
          item.title,
          [item.text, item.ocrText, ...(item.filePaths ?? [])]
            .filter(Boolean)
            .join("\n"),
        );
      });
      ctx.events.emit("clipboard.changed", { item });
    };
    const remove = async (ids: string[]) => {
      const items = ids.map(get).filter((i): i is ClipboardItem => !!i);
      ctx.db.transaction(() => {
        for (const item of items) {
          ctx.db.run("DELETE FROM clipboard_history WHERE id = ?", item.id);
          ctx.db.run("DELETE FROM clipboard_fts WHERE id = ?", item.id);
        }
      });
      for (const item of items)
        if (item.imagePath && dirname(item.imagePath) === imageDir)
          await unlink(item.imagePath).catch(() => {});
      if (items.length)
        ctx.events.emit("clipboard.itemsChanged", {
          ids: items.map((i) => i.id),
          deleted: true,
        });
    };
    const prune = async () => {
      const duration = retentionMs(
        ctx.settings.get("clipboard.keepHistoryFor"),
      );
      if (duration !== null)
        await remove(
          ctx.db
            .all<{
              id: string;
            }>(
              "SELECT id FROM clipboard_history WHERE pinned=0 AND last_copied_at < ?",
              Date.now() - duration,
            )
            .map((r) => r.id),
        );
    };
    let queue = Promise.resolve();
    const ingest = async (snapshot: ClipboardSnapshot) => {
      if (retentionMs(ctx.settings.get("clipboard.keepHistoryFor")) === 0)
        return;
      const disabled = ctx.settings.get("clipboard.disabledApplications");
      if (
        snapshot.sourceApp &&
        disabled.some(
          (a) =>
            a === snapshot.sourceApp!.bundleId ||
            a === snapshot.sourceApp!.path,
        )
      )
        return;
      if (!classifyClipboard(snapshot)) return;
      if (
        snapshot.primary.kind === "file" &&
        !ctx.settings.get("clipboard.saveFiles")
      )
        return;
      let path: string | undefined;
      let hash: string | undefined;
      if (snapshot.primary.kind === "image") {
        if (!ctx.settings.get("clipboard.saveImages")) return;
        const bytes = snapshot.primary.base64
          ? Buffer.from(snapshot.primary.base64, "base64")
          : await readFile(snapshot.primary.path!);
        if (!bytes.length || bytes.length > 50 * 1024 * 1024) return;
        hash = createHash("sha256").update(bytes).digest("hex");
        await mkdir(imageDir, { recursive: true });
        path = join(imageDir, `${hash}.png`);
        await writeFile(path, bytes, { mode: 0o600 });
      }
      const item = classifyClipboard(snapshot, path, hash)!;
      const existing = ctx.db.get<Row>(
        "SELECT id,data FROM clipboard_history WHERE content_hash = ?",
        item.contentHash,
      );
      if (existing) {
        const old: ClipboardItem = JSON.parse(existing.data);
        persist({
          ...old,
          sourceApp: item.sourceApp,
          lastCopiedAt: item.lastCopiedAt,
          copyCount: old.copyCount + 1,
        });
      } else persist(item);
    };
    ctx.onShutdown(
      ctx.native.on("clipboard.changed", (snapshot) => {
        queue = queue
          .then(() => ingest(snapshot))
          .catch(() => ctx.log.warn("Clipboard ingestion failed"));
      }),
    );
    const monitor = () =>
      ctx.native.call("clipboard.setMonitoring", {
        enabled:
          retentionMs(ctx.settings.get("clipboard.keepHistoryFor")) !== 0,
        ignoredBundleIds: ctx.settings.get("clipboard.disabledApplications"),
      });
    ctx.onReady(async () => {
      await monitor();
      await prune();
    });
    ctx.onShutdown(
      ctx.settings.onChange((key) => {
        if (
          key === "clipboard.disabledApplications" ||
          key === "clipboard.keepHistoryFor"
        )
          background(ctx, monitor(), "Clipboard monitoring");
        if (key === "clipboard.keepHistoryFor")
          background(ctx, prune(), "Clipboard retention");
      }),
    );
    const timer = setInterval(
      () => background(ctx, prune(), "Clipboard retention"),
      3600000,
    );
    timer.unref();
    ctx.onShutdown(async () => {
      clearInterval(timer);
      await queue;
      await ctx.native.call("clipboard.setMonitoring", { enabled: false });
    });
    ctx.rpc.handleAll({
      "clipboard.list": ({ query = "", kind = "all", limit, offset = 0 }) => {
        const match = ftsQuery(query);
        const clauses = [];
        const args: (string | number)[] = [];
        if (match) {
          clauses.push(
            "id IN (SELECT id FROM clipboard_fts WHERE clipboard_fts MATCH ?)",
          );
          args.push(match);
        } else if (query.trim()) return { items: [], total: 0 };
        if (kind !== "all") {
          clauses.push("kind = ?");
          args.push(kind);
        }
        const where = clauses.length ? `WHERE ${clauses.join(" AND ")}` : "";
        const total = ctx.db.get<{ n: number }>(
          `SELECT count(*) n FROM clipboard_history ${where}`,
          ...args,
        )!.n;
        return {
          total,
          items: ctx.db
            .all<Row>(
              `SELECT id,data FROM clipboard_history ${where} ORDER BY pinned DESC,last_copied_at DESC LIMIT ? OFFSET ?`,
              ...args,
              boundedLimit(limit),
              boundedLimit(offset, 0, 1e7),
            )
            .map((r) => JSON.parse(r.data)),
        };
      },
      "clipboard.get": ({ id }) => get(id),
      "clipboard.paste": async ({ id, plainText }) => {
        await ctx.native.call("input.paste", {
          content: clipboardContent(required(id), plainText),
        });
      },
      "clipboard.copy": async ({ id, plainText }) => {
        await ctx.native.call("clipboard.write", {
          content: clipboardContent(required(id), plainText),
        });
      },
      "clipboard.pin": ({ id, pinned }) => {
        persist({ ...required(id), pinned });
      },
      "clipboard.delete": ({ id }) => remove([id]),
      "clipboard.clear": ({ includePinned = false }) =>
        remove(
          ctx.db
            .all<{
              id: string;
            }>(
              `SELECT id FROM clipboard_history ${includePinned ? "" : "WHERE pinned=0"}`,
            )
            .map((r) => r.id),
        ),
      "clipboard.pasteSequentially": async ({ ids }) => {
        if (!ids.length || ids.length > 1000)
          throw RpcError.invalidParams(
            "Select between 1 and 1000 clipboard items",
          );
        await ctx.native.call("clipboard.setSequentialPaste", {
          contents: ids.map((id) => clipboardContent(required(id))),
        });
      },
    });
  },
};
