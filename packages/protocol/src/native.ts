/**
 * Native host (Swift/AppKit) API.
 *
 * Callers:
 *   - the backend, over stdio NDJSON JSON-RPC (method names exactly as below);
 *   - the frontend, through `window.webkit.messageHandlers.native.postMessage({ method, params })`
 *     which resolves with `{ result }` or `{ error }` (WKScriptMessageHandlerWithReply).
 *
 * The native host also sends notifications (NativeEvents) to the backend over stdio
 * and to every web view by calling `window.__surgecastNative.emit(topic, payload)`.
 *
 * Every method must answer. Methods that need a missing macOS permission fail with
 * RpcErrorCode.PermissionDenied and `data: { permission }`.
 */

import type { Hotkey, ImageLike } from "./ui";

export type PermissionKind =
  | "accessibility"
  | "screenRecording"
  | "calendar"
  | "reminders"
  | "contacts"
  | "fullDiskAccess"
  | "automation"
  | "inputMonitoring"
  | "location"
  | "microphone";

export type PermissionStatus = "granted" | "denied" | "notDetermined" | "restricted" | "unknown";

export type WindowKind = "main" | "ai-chat" | "notes" | "settings" | "welcome" | "theme-studio";

export interface AppInfo {
  name: string;
  bundleId?: string;
  path: string;
  version?: string;
  /** true for apps in /System/Library/CoreServices etc. that Raycast lists (Finder, ...). */
  isSystem?: boolean;
}

export interface RunningAppInfo extends AppInfo {
  pid: number;
  isActive: boolean;
  isHidden: boolean;
}

export type ClipboardContent =
  | { kind: "text"; text: string; html?: string; rtf?: string }
  | { kind: "file"; paths: string[] }
  | { kind: "image"; path?: string; base64?: string; uti?: string; width?: number; height?: number }
  | { kind: "color"; hex: string };

export interface ClipboardSnapshot {
  changeCount: number;
  /** Highest-fidelity representation. */
  primary: ClipboardContent;
  /** Plain text representation if one exists (also for file/url items). */
  text?: string;
  html?: string;
  /** Pasteboard UTIs present, for filtering. */
  types: string[];
  sourceApp?: AppInfo;
  /** org.nspasteboard.ConcealedType / TransientType / AutoGeneratedType markers. */
  concealed: boolean;
  transient: boolean;
}

export interface ScreenInfo {
  id: number;
  name: string;
  frame: { x: number; y: number; width: number; height: number };
  visibleFrame: { x: number; y: number; width: number; height: number };
  scale: number;
  isMain: boolean;
}

/**
 * Window management commands. Keys match Raycast's built-in command keys.
 * The native host owns the geometry for every command (gaps applied inside).
 */
export type WindowCommand =
  | "maximize" | "restore" | "minimize" | "minimizeOnDisplay" | "maximizeHeight" | "maximizeWidth"
  | "maximizeAlmost" | "reasonableSize" | "center" | "centerHalf"
  | "leftHalf" | "rightHalf" | "topHalf" | "bottomHalf"
  | "firstThird" | "centerThird" | "lastThird" | "firstTwoThird" | "centerTwoThird" | "lastTwoThird"
  | "firstThreeFourth" | "centerThreeFourth" | "lastThreeFourth"
  | "topThird" | "middleThird" | "bottomThird" | "topTwoThird" | "bottomTwoThird"
  | "topFirstFourth" | "topSecondFourth" | "topThirdFourth" | "topLastFourth" | "topThreeFourth" | "bottomThreeFourth"
  | "topCenterTwoThird" | "bottomCenterTwoThird"
  | "firstFourth" | "secondFourth" | "thirdFourth" | "lastFourth"
  | "topLeftSixth" | "topCenterSixth" | "topRightSixth" | "bottomLeftSixth" | "bottomCenterSixth" | "bottomRightSixth"
  | "topLeftQuarter" | "topRightQuarter" | "bottomLeftQuarter" | "bottomRightQuarter"
  | "moveLeft" | "moveRight" | "moveTop" | "moveBottom"
  | "movePreviousDisplay" | "moveNextDisplay"
  | "movePreviousDesktop" | "moveNextDesktop" | "switchToPreviousSpace" | "switchToNextSpace"
  | "makeSmaller" | "makeLarger" | "toggleFullscreen" | "toggleAlwaysOnTop"
  | "focusNextAppWindow" | "focusPreviousAppWindow";

/** A custom window layout as fractions of the screen's visible frame (0..1). */
export interface WindowLayoutRect {
  x: number;
  y: number;
  width: number;
  height: number;
}

export interface CalendarInfo {
  id: string;
  title: string;
  color: string;
  source: string;
  allowsModifications: boolean;
}

export interface CalendarEvent {
  id: string;
  calendarId: string;
  title: string;
  location?: string;
  notes?: string;
  url?: string;
  start: string; // ISO
  end: string; // ISO
  isAllDay: boolean;
  color: string;
  /** Meeting link detected in location/notes/url (Zoom, Meet, Teams, ...). */
  conferenceUrl?: string;
  attendees?: { name?: string; email?: string; status?: string }[];
}

export interface MenuItemInfo {
  /** Path of titles from the menu bar, e.g. ["File", "Export", "PDF…"]. */
  path: string[];
  title: string;
  shortcut?: string;
  enabled: boolean;
  checked?: boolean;
}

export interface MenuBarExtraItem {
  id: string;
  title?: string;
  subtitle?: string;
  icon?: ImageLike;
  tooltip?: string;
  shortcut?: Hotkey;
  kind: "item" | "separator" | "section" | "submenu";
  enabled?: boolean;
  children?: MenuBarExtraItem[];
}

export interface NativeMethods {
  // --- app & windows -------------------------------------------------------
  "app.info": { params: void; result: { version: string; build: string; macOSVersion: string; macOSMajor: number; arch: string; bundlePath: string; dataDir: string } };
  "app.quit": { params: void; result: void };
  "app.relaunch": { params: void; result: void };
  "app.setLaunchAtLogin": { params: { enabled: boolean }; result: void };
  "app.setMenuBarIconVisible": { params: { visible: boolean }; result: void };
  "app.setDockIconVisible": { params: { visible: boolean }; result: void };

  "window.show": { params: { kind: WindowKind; route?: string; payload?: unknown }; result: void };
  "window.hide": { params: { kind: WindowKind; restoreFocus?: boolean }; result: void };
  "window.toggle": { params: { kind: WindowKind }; result: void };
  "window.close": { params: { kind: WindowKind }; result: void };
  /** Main window only: height of the content in points (collapsed vs expanded). */
  "window.setContentHeight": { params: { kind: WindowKind; height: number; animate?: boolean }; result: void };
  "window.setSize": { params: { kind: WindowKind; width: number; height: number }; result: void };
  "window.setFloating": { params: { kind: WindowKind; floating: boolean }; result: void };
  "window.isVisible": { params: { kind: WindowKind }; result: boolean };
  "window.startDrag": { params: { kind: WindowKind }; result: void };

  // --- applications -----------------------------------------------------------
  "apps.list": { params: { refresh?: boolean }; result: AppInfo[] };
  "apps.running": { params: void; result: RunningAppInfo[] };
  "apps.frontmost": { params: void; result: RunningAppInfo | null };
  /** The app that was frontmost before Surgecast's main window opened. */
  "apps.previous": { params: void; result: RunningAppInfo | null };
  "apps.defaultForPath": { params: { path: string }; result: AppInfo | null };
  "apps.forUrl": { params: { url: string }; result: AppInfo[] };
  "apps.activate": { params: { bundleIdOrPath: string }; result: void };
  "apps.hide": { params: { bundleIdOrPath: string }; result: void };
  "apps.quit": { params: { bundleIdOrPath: string; force?: boolean }; result: void };

  // --- opening ---------------------------------------------------------------
  "open.url": { params: { url: string; app?: string; background?: boolean }; result: void };
  "open.path": { params: { path: string; app?: string }; result: void };
  "open.showInFinder": { params: { path: string }; result: void };
  "open.trash": { params: { paths: string[] }; result: void };
  "open.quickLook": { params: { path: string }; result: void };

  // --- clipboard & input ---------------------------------------------------
  "clipboard.read": { params: void; result: ClipboardSnapshot | null };
  "clipboard.write": { params: { content: ClipboardContent; concealed?: boolean; transient?: boolean }; result: void };
  /** Queue items for successive physical Cmd-V presses; native consumes one item per press. */
  "clipboard.setSequentialPaste": { params: { contents: ClipboardContent[] }; result: void };
  "clipboard.clear": { params: void; result: void };
  /** Start/stop emitting `clipboard.changed`. Poll interval in ms (default 300). */
  "clipboard.setMonitoring": { params: { enabled: boolean; intervalMs?: number; ignoredBundleIds?: string[] }; result: void };
  /**
   * Hide Surgecast, restore focus to the previous app, put `content` on the
   * pasteboard and press ⌘V. Restores the old pasteboard afterwards when
   * `restoreClipboard` is true (used by snippets).
   */
  "input.paste": { params: { content: ClipboardContent; restoreClipboard?: boolean }; result: void };
  "input.typeText": { params: { text: string }; result: void };
  "input.pressKeys": { params: { key: string; modifiers?: string[] }; result: void };
  /** Accessibility API first, then a ⌘C round-trip fallback. */
  "input.selectedText": { params: void; result: string | null };
  "input.selectedFinderItems": { params: void; result: string[] };

  // --- hotkeys & text expansion ----------------------------------------------
  "hotkeys.register": { params: { id: string; hotkey: Hotkey }; result: { ok: boolean; conflict?: string } };
  "hotkeys.unregister": { params: { id: string }; result: void };
  "hotkeys.unregisterAll": { params: void; result: void };
  /** Start the native recorder; resolves with the next pressed combination or null on Esc. */
  "hotkeys.record": { params: void; result: Hotkey | null };
  /**
   * Snippet keyword expansion. Native watches typed characters (CGEventTap).
   * When the typed buffer ends with a keyword, native sends the backend the
   * request `snippets.resolve` (see BackendForNativeMethods), deletes the
   * keyword with backspaces, pastes the returned text (restoring the
   * clipboard), and moves the caret left by `cursorOffset` characters.
   */
  "snippets.setKeywords": { params: { keywords: { id: string; keyword: string }[]; enabled: boolean; ignoredBundleIds?: string[] }; result: void };

  // --- window management ---------------------------------------------------
  "windows.run": { params: { command: WindowCommand; gap?: number }; result: void };
  "windows.applyLayout": { params: { rect: WindowLayoutRect; gap?: number }; result: void };
  "windows.undo": { params: void; result: void };
  "windows.screens": { params: void; result: ScreenInfo[] };
  "windows.focused": { params: void; result: { app: AppInfo; title: string; frame: WindowLayoutRect } | null };

  // --- system ------------------------------------------------------------------
  "system.run": {
    params: {
      /** Keys match Raycast's System Actions command keys. */
      action:
        | "dismissNotifications" | "ejectAllDisks" | "openTrash" | "emptyTrash"
        | "hideAllAppsExceptFrontmost" | "lockScreen" | "logOut"
        | "quitAllApplications" | "quitAllApplicationsExceptFrontmost" | "quitActiveApplication"
        | "restart" | "shutDown" | "sleep" | "hibernate" | "sleepDisplays"
        | "toggleMuteCurrentApp" | "setVolume" | "turnVolumeUp" | "turnVolumeDown" | "toggleMute"
        | "playPause" | "nextTrack" | "previousTrack"
        | "showDesktop" | "showScreenSaver"
        | "toggleWifi" | "toggleBluetooth" | "toggleEnergySaver" | "toggleHiddenFiles"
        | "toggleStageManager" | "toggleSystemAppearance" | "toggleMicrophoneMute"
        | "unhideAllHiddenApps";
      /** e.g. 0..100 for setVolume. */
      value?: unknown;
    };
    result: void;
  };
  "system.appearance": { params: void; result: "dark" | "light" };
  "system.volume": { params: void; result: { volume: number; muted: boolean } };
  "system.runAppleScript": { params: { script: string; language?: "AppleScript" | "JavaScript" }; result: string };
  "system.notification": { params: { title: string; body?: string }; result: void };

  // --- permissions & secrets ----------------------------------------------------
  "permissions.status": { params: void; result: Record<PermissionKind, PermissionStatus> };
  "permissions.request": { params: { kind: PermissionKind }; result: PermissionStatus };
  "permissions.openSettings": { params: { kind: PermissionKind }; result: void };
  "keychain.get": { params: { account: string }; result: string | null };
  "keychain.set": { params: { account: string; value: string }; result: void };
  "keychain.delete": { params: { account: string }; result: void };

  // --- data sources needing frameworks ----------------------------------------
  "calendar.calendars": { params: void; result: CalendarInfo[] };
  "calendar.events": { params: { from: string; to: string; calendarIds?: string[] }; result: CalendarEvent[] };
  "menus.list": { params: { bundleId?: string }; result: MenuItemInfo[] };
  "menus.press": { params: { bundleId?: string; path: string[] }; result: void };
  "files.icon": { params: { path: string; size: number }; result: { pngBase64: string } };
  "files.metadata": { params: { path: string }; result: { kind?: string; size?: number; created?: string; modified?: string; lastOpened?: string; uti?: string; where?: string } };
  "screen.capture": { params: { mode: "interactive" | "window" | "screen"; path?: string }; result: { path: string } | null };
  "speech.say": { params: { text: string; voice?: string }; result: void };

  // --- overlays ------------------------------------------------------------------
  "hud.show": { params: { text: string; icon?: string; durationMs?: number }; result: void };
  "confetti.show": { params: void; result: void };
  "alert.show": { params: { title: string; message?: string; buttons: string[]; style?: "informational" | "warning" | "critical" }; result: { index: number } };

  // --- menu bar extras (extension "menu-bar" commands) --------------------------
  "menubar.set": { params: { id: string; title?: string; icon?: ImageLike; tooltip?: string; items: MenuBarExtraItem[] }; result: void };
  "menubar.remove": { params: { id: string }; result: void };
}

export type NativeMethod = keyof NativeMethods;
export type NativeParams<M extends NativeMethod> = NativeMethods[M]["params"];
export type NativeResult<M extends NativeMethod> = NativeMethods[M]["result"];

/** Notifications the native host emits (to backend over stdio and to all web views). */
export interface NativeEvents {
  "native.ready": { version: string; macOSMajor: number };
  "hotkey.pressed": { id: string };
  "clipboard.changed": ClipboardSnapshot;
  "window.didShow": { kind: WindowKind };
  "window.didHide": { kind: WindowKind };
  "window.didBecomeKey": { kind: WindowKind };
  "window.didResignKey": { kind: WindowKind };
  "appearance.changed": { appearance: "dark" | "light" };
  "apps.changed": { reason: "installed" | "removed" | "updated" };
  "frontmost.changed": { app: RunningAppInfo | null };
  "menubar.itemClicked": { menuId: string; itemId: string };
  "menubar.opened": { menuId: string };
  /** A deeplink such as surgecast://extensions/... or raycast://... was opened. */
  "url.opened": { url: string };
  "permissions.changed": { kind: PermissionKind; status: PermissionStatus };
  "system.willSleep": Record<string, never>;
  "system.didWake": Record<string, never>;
}

/**
 * Methods the backend implements for the native host (native -> backend requests).
 */
export interface BackendForNativeMethods {
  /** Resolve a snippet's text with dynamic placeholders at expansion time. */
  "snippets.resolve": { params: { id: string; keyword: string }; result: { text: string; cursorOffset?: number } | null };
  /** The backend's channel for native: health check. */
  "backend.ping": { params: void; result: { ok: true } };
}
